/**
 * Build the page that gets published as an Artifact.
 *
 * Vite writes hashed filenames and empties dist/ on every build, so a
 * hand-written entry page is both stale and deleted each time the app is
 * rebuilt. This regenerates it from whatever is actually in dist/.
 *
 * Run after `vite build --base=./`, then publish dist/play.html with
 * everything in dist/assets alongside it.
 */
import { readdirSync, writeFileSync } from 'node:fs'

const assets = readdirSync('dist/assets')
const js = assets.find((f) => /^index-.*\.js$/.test(f))
const css = assets.find((f) => /^index-.*\.css$/.test(f))
if (!js) throw new Error('no entry bundle in dist/assets - run the build first')

const page = `<title>The Homestead</title>

<!--
  The Homestead, built for playing away from the desk.

  This is the real app rather than a cut-down version: the same bundle
  Vite produces for the dev server, published with its assets beside it.
  Nothing loads from anywhere else, which is what the artifact sandbox
  requires and also why it keeps working with no connection once open.

  Progress lives in this page's own storage, which is per-device. A phone
  keeps its own farm, purses and snake skins; it is not the save from the
  desktop and the two never meet.

  Generated by scripts/make-artifact.mjs - overwritten on every build.
-->

<script>
  // Tell the phone the page is phone-sized.
  //
  // The artifact wrapper owns the document head, so this cannot be a
  // plain meta tag here. Without it a phone pretends it is 980 pixels
  // wide and then shrinks the whole page to fit the screen, which draws
  // thirteen-pixel text at about five and makes every control in the
  // game too small to read or hit. Setting it before the app mounts gets
  // everything drawn at its real size.
  (function () {
    var m = document.querySelector('meta[name=viewport]')
    if (!m) {
      m = document.createElement('meta')
      m.name = 'viewport'
      document.head.appendChild(m)
    }
    m.content = 'width=device-width, initial-scale=1, viewport-fit=cover'
  })()
</script>

<style>
  html,
  body {
    margin: 0;
    padding: 0;
    background: #101a12;
    min-height: 100%;
    /* Every game is driven by dragging on a canvas. Without this, a drag
       scrolls the page out from under the player instead. */
    overscroll-behavior: none;
  }
  #root {
    min-height: 100vh;
  }
  canvas {
    touch-action: none;
    /* Drawn at a fixed 960 wide; let it shrink rather than run off the
       side of a narrow screen. */
    max-width: 100vw;
    height: auto;
  }

  /*
    Touch sizing.

    The game sets its styles inline from React, so an ordinary rule loses
    to them and these have to be marked important to land at all. They
    are scoped to coarse pointers, so the desktop layout never sees any
    of it.

    Both Apple and Google put the smallest comfortable target at roughly
    44 points. Several of these controls were eleven-pixel text in a
    twenty-pixel box.
  */
  @media (pointer: coarse) {
    button {
      min-height: 44px !important;
      font-size: 15px !important;
      line-height: 1.35 !important;
    }
    /* Cards stack three lines inside one button; let the lines stay
       smaller than the button's own text or the card bursts. */
    button > span,
    button > span > span {
      font-size: 13px !important;
      min-height: 0 !important;
    }
    input[type='checkbox'] {
      width: 22px !important;
      height: 22px !important;
    }
  }
</style>

<div id="root"></div>
${css ? `<link rel="stylesheet" href="assets/${css}" />\n` : ''}<script type="module" src="assets/${js}"></script>
`

writeFileSync('dist/play.html', page)
console.log('dist/play.html ->', js, css ?? '(no css)')
