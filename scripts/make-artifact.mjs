/**
 * Build the page that gets published as an Artifact.
 *
 * Vite writes hashed filenames, and `vite build` empties dist/ first, so
 * a hand-written entry page is both stale and deleted every time the app
 * is rebuilt. This regenerates it from whatever is actually in dist/.
 *
 * Run it after `vite build --base=./`, then publish dist/play.html with
 * everything in dist/assets alongside it.
 */
import { readdirSync, writeFileSync } from 'node:fs'

const assets = readdirSync('dist/assets')
const js = assets.find((f) => /^index-.*\.js$/.test(f))
const css = assets.find((f) => /^index-.*\.css$/.test(f))
if (!js) throw new Error('no entry bundle in dist/assets - run the build first')

writeFileSync(
  'dist/play.html',
  `<title>The Homestead</title>

<!--
  The Homestead, built for playing away from the desk.

  This is the real app rather than a cut-down version: the same bundle
  Vite produces for the dev server, published with its assets beside it.
  Nothing loads from anywhere else, which is what the artifact sandbox
  requires and also why it keeps working with no connection once open.

  Progress lives in this page's own storage, which is per-device. A
  phone keeps its own farm, purses and snake skins; it is not the save
  from the desktop and the two never meet.

  Generated by scripts/make-artifact.mjs - do not edit by hand, it is
  overwritten on every build.
-->

<style>
  html,
  body {
    margin: 0;
    padding: 0;
    background: #101a12;
    min-height: 100%;
    /* Every game is driven by dragging on a canvas. Without this a drag
       scrolls the page out from under the player instead. */
    overscroll-behavior: none;
  }
  #root {
    min-height: 100vh;
  }
  canvas {
    touch-action: none;
    /* Drawn at a fixed 960 wide; let it shrink rather than run off the
       side of a narrow screen. */
    max-width: 100vw;
    height: auto;
  }
</style>

<div id="root"></div>
${css ? `<link rel="stylesheet" href="assets/${css}" />\n` : ''}<script type="module" src="assets/${js}"></script>
`
)
console.log('dist/play.html ->', js, css ?? '(no css)')
